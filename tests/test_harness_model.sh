#!/usr/bin/env bash
set -u
root="${ST_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
v=1.60.0
fail=0
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
cov="coverage-skills coverage-agents coverage-hooks coverage-statusline coverage-scripts coverage-procedures coverage-data"
[ $# -gt 0 ] || set -- coverage missing summaries links kinds vendored views page readme nomcp validate rebuild

gate() {
  command -v npx >/dev/null && command -v node >/dev/null || { echo "SKIP $1: npx not found"; return 1; }
  nv=$(node --version)
  python3 -c 'import sys; sys.exit(0 if tuple(int(x) for x in sys.argv[1].lstrip("v").split(".")) >= (22, 22, 3) else 1)' "$nv" || { echo "SKIP $1: node $nv is below 22.22.3"; return 1; }
}

validate() {
  gate validate || return 0
  compgen -G "$root/docs/harness/*/*.c4" >/dev/null || { echo "FAIL validate: docs/harness has no .c4 files"; fail=1; return 0; }
  if out=$(npx -y "likec4@$v" validate "$root/docs/harness" 2>&1); then
    echo "ok   validate: docs/harness validates with likec4@$v"
  else
    echo "FAIL validate: likec4 validate failed"
    printf '%s\n' "$out" | head -n 20
    fail=1
  fi
}

rebuild() {
  gate rebuild || return 0
  h=$(mktemp -d "$tmp/XXXXXX")
  if ! cp -r "$root/docs/harness" "$h/" 2>/dev/null; then
    echo "FAIL rebuild: page is not rebuilt, docs/harness cannot be copied"
    fail=1
    return 0
  fi
  rm -f "$h/harness/README.md"
  if ! out=$(npx -y "likec4@$v" export markdown "$h/harness" 2>&1); then
    echo "FAIL rebuild: export markdown failed"
    printf '%s\n' "$out" | head -n 20
    fail=1
    return 0
  fi
  d=$(diff "$root/docs/harness/README.md" "$h/harness/README.md" 2>&1)
  if [ -n "$d" ]; then
    echo "FAIL rebuild: page is not rebuilt"
    printf '%s\n' "$d" | head -n 10
    fail=1
  else
    echo "ok   rebuild: docs/harness/README.md is what export markdown makes"
  fi
}

py() {
  python3 - "$root" "$v" "$1" <<'PY' || fail=1
import glob, os, re, sys

root, v, name = sys.argv[1], sys.argv[2], sys.argv[3]
DOCS = "docs/harness"
bad = []
STR = r"'(?:[^'\\]|\\.)*'"
STR_RE = re.compile(STR)
DECL = re.compile(r"^\s*([a-z0-9-]+) = ([a-z]+) " + STR + r"\s*(\{)?\s*$")
EXT = re.compile(r"^\s*extend ([a-z0-9-]+) \{\s*$")
FIELD = re.compile(r"^\s*(summary|path|data) '((?:[^'\\]|\\.)*)'\s*$")
TAG = re.compile(r"^\s*#(\w+)\s*$")
LINK = re.compile(r"^\s*[a-z0-9][a-z0-9.-]* -\[(starts|reads|writes|runs|passes)\]-> [a-z0-9][a-z0-9.-]* '(?:[^'\\]|\\.)+'\s*$")
DYN = re.compile(r"^\s*dynamic view ([a-z0-9-]+) \{")
ARROW = re.compile(r"^\s*\S+\s+-(?:\[\w+\]-)?>\s+\S+\s+'((?:[^'\\]|\\.)*)'\s*$")
NUMBERED = re.compile(r"^\((\d+)\) (.*)$")
STRATUM = re.compile(rb"\.stratum/[A-Za-z0-9_-]+(?:\.[a-z]+)?")
ALLOWED = re.compile(r"^(likec4\.config\.json|README\.md|model/[^/]+\.c4|views/[^/]+\.c4|\.likec4/[^/]+\.likec4\.snap)$")
SPEC = {
    "element": {"group", "actor", "event", "skill", "agent", "hook", "statusline", "script", "procedure", "pluginfile", "datafile"},
    "relationship": {"starts", "reads", "writes", "runs", "passes"},
    "tag": {"vendored"},
}
GATES = {"full": 3, "fast": 1, "design": 1}
ACTORS = ["user", "codex", "advisor", "github"]
MARK = "<!-- Generated by likec4 export markdown. Do not edit manually. -->"
HEADS = ["Full lane", "Fast lane", "Quick lane", "Design lane", "Agents", "Harness", "Data flow"]
FEATURE = ["spec.md", "plan.md", "research.md", "data-model.md", "contracts", "quickstart.md", "tasks.md", "checklists", "changes", "decisions.md", "advisor.md", "gaps.md"]
# ponytail: vendored list copied from data-model.md, edit both when a vendored skill changes
VENDORED = ["st-ponytail", "st-ponytail-review", "st-ponytail-audit", "st-ponytail-debt", "st-ponytail-gain", "st-ponytail-help", "st-grill", "st-ui-ux", "st-impeccable", "st-graphify", "st-hallmark"]


def at(*p):
    return os.path.join(root, *p)


def rel(p):
    return os.path.relpath(p, root).replace(os.sep, "/")


def fail(msg):
    bad.append(msg)
    print(f"FAIL {name}: {msg}")


def done(msg):
    if not bad:
        print(f"ok   {name}: {msg}")


def parse():
    els, bare, links = [], [], []
    for f in sorted(glob.glob(at(DOCS, "model", "*.c4"))):
        fr, depth, stack, ctx = rel(f), 0, [], []
        for n, line in enumerate(open(f, encoding="utf-8"), 1):
            line = line.rstrip("\n")
            if "->" in line:
                links.append((fr, n, line))
            d, e, fd, tg = DECL.match(line), EXT.match(line), FIELD.match(line), TAG.match(line)
            if d:
                el = {"id": (ctx[-1][0] + "." if ctx else "") + d[1], "kind": d[2], "file": fr, "line": n, "start": depth, "fields": [], "tags": set()}
                (stack if d[3] else bare).append(el)
            elif e:
                ctx.append((e[1], depth))
            elif stack and fd:
                stack[-1]["fields"].append((fd[1], fd[2]))
            elif stack and tg:
                stack[-1]["tags"].add(tg[1])
            code = STR_RE.sub("", line)
            depth += code.count("{") - code.count("}")
            while stack and stack[-1]["start"] >= depth:
                els.append(stack.pop())
            while ctx and ctx[-1][1] >= depth:
                ctx.pop()
    for el in els:
        el["summary"] = [x for k, x in el["fields"] if k == "summary"]
        el["path"] = next((x for k, x in el["fields"] if k == "path"), None)
        el["data"] = next((x for k, x in el["fields"] if k == "data"), None)
    return els, bare, links


def stratum_names():
    names = set()
    for d in ["scripts", "hooks", "statusline", "skills", "agents", "procedures"]:
        for dp, _, fn in os.walk(at(d)):
            for f in fn:
                b = open(os.path.join(dp, f), "rb").read()
                if b"\0" not in b:
                    names.update(m.decode() for m in STRATUM.findall(b))
    return names


def listing(d, keep=lambda p: True, recurse=False):
    base = at(d)
    if not os.path.isdir(base):
        fail(f"{d}/ does not exist")
        return []
    if recurse:
        found = [rel(os.path.join(dp, f)) for dp, _, fn in os.walk(base) for f in fn if "__pycache__" not in dp]
    else:
        found = [f"{d}/{f}" for f in os.listdir(base)]
    return sorted(p for p in found if keep(p))


def cover(items, key):
    have = {e[key] for e in parse()[0]}
    for i in items:
        if i not in have:
            fail(f"{i} has no element")
    done(f"all {len(items)} have an element")


def c_skills():
    cover(listing("skills", lambda p: os.path.isdir(at(p))), "path")


def c_agents():
    cover(listing("agents", lambda p: p.endswith(".md")), "path")


def c_hooks():
    cover(listing("hooks", lambda p: not p.endswith(".pyc"), True), "path")


def c_statusline():
    cover(listing("statusline", recurse=True), "path")


def c_scripts():
    cover(listing("scripts", lambda p: p.endswith(".sh")), "path")


def c_procedures():
    cover(listing("procedures", lambda p: p.endswith(".md")), "path")


def c_data():
    cover(sorted(stratum_names()) + ["specs/NNN-feature/" + f for f in FEATURE], "data")


def c_missing():
    els = parse()[0]
    names = stratum_names()
    for e in els:
        if e["path"] and not os.path.exists(at(e["path"])):
            fail(f"{e['path']} does not exist")
        if e["data"] and e["data"].startswith(".stratum/") and e["data"] not in names:
            fail(f"{e['data']} is not named in the harness code")
    done("every path exists and every .stratum name is in the code")


def c_summaries():
    els, bare, _ = parse()
    for b in bare:
        fail(f"{b['id']} has no block")
    for e in els:
        s = e["summary"]
        if len(s) != 1:
            fail(f"{e['id']} has {len(s)} summary lines, expected 1")
        elif not 1 <= len(s[0]) <= 200:
            fail(f"{e['id']} summary is {len(s[0])} characters, expected 1 to 200")
        elif len(re.split(r"(?<=[.!?])\s+", s[0].strip())) > 2:
            fail(f"{e['id']} summary has more than 2 sentences")
    done(f"{len(els)} elements have one summary each")


def c_links():
    ls = parse()[2]
    for fr, n, line in ls:
        if not LINK.match(line):
            fail(f"{fr}:{n} is not a source -[kind]-> target 'label' line")
    done(f"{len(ls)} relationship lines have a kind and a label")


def c_kinds():
    spec = at(DOCS, "model", "0-spec.c4")
    if not os.path.isfile(spec):
        return fail(f"{DOCS}/model/0-spec.c4 does not exist")
    block = re.search(r"^specification \{$(.*?)^\}$", open(spec, encoding="utf-8").read(), re.M | re.S)
    if not block:
        return fail(f"{DOCS}/model/0-spec.c4 has no specification block")
    found = {k: set() for k in SPEC}
    for k, x in re.findall(r"^\s*(element|relationship|tag) (\S+)\s*$", block[1], re.M):
        found[k].add(x)
    for k, want in SPEC.items():
        for x in sorted(found[k] - want):
            fail(f"{x} is not an allowed {k}")
        for x in sorted(want - found[k]):
            fail(f"{x} is missing as {k}")
    for f in glob.glob(at(DOCS, "model", "*.c4")):
        if f != spec and re.search(r"^specification \{", open(f, encoding="utf-8").read(), re.M):
            fail(f"{rel(f)} has a specification block")
    done("11 element kinds, 5 relationship kinds and the tag vendored")


def c_vendored():
    els = parse()[0]
    want = {"skills/" + s for s in VENDORED}
    for e in els:
        if e["path"] in want and "vendored" not in e["tags"]:
            fail(f"{e['id']} lacks #vendored")
        if e["path"] not in want and "vendored" in e["tags"]:
            fail(f"{e['id']} has #vendored but is not a vendored skill")
    done(f"{sum(e['path'] in want for e in els)} of {len(VENDORED)} vendored skills have #vendored")


def c_views():
    for f in sorted(glob.glob(at(DOCS, "model", "*.c4")) + glob.glob(at(DOCS, "views", "*.c4"))):
        for n, line in enumerate(open(f, encoding="utf-8"), 1):
            if "`" in line:
                fail(f"{rel(f)}:{n} has a backtick")
    for f in sorted(glob.glob(at(DOCS, "views", "*.c4"))):
        lines = open(f, encoding="utf-8").read().splitlines()
        vid = next((DYN.match(x)[1] for x in lines if DYN.match(x)), None)
        if vid is None:
            continue
        steps, gates = 0, 0
        for n, line in enumerate(lines, 1):
            if "->" not in line:
                continue
            a = ARROW.match(line)
            k = NUMBERED.match(a[1]) if a else None
            if k is None:
                fail(f"{vid} line {n} has no (n) label")
                continue
            steps += 1
            if int(k[1]) != steps:
                fail(f"{vid} step {steps} is labelled ({k[1]}), expected ({steps})")
            gates += k[2].startswith("gate: ")
        if gates < GATES.get(vid, 0):
            fail(f"{vid} has {gates} gate steps, needs {GATES[vid]}")
    declared = {e["id"] for e in parse()[0] if e["kind"] == "actor" and e["file"] == f"{DOCS}/model/0-spec.c4"}
    for a in ACTORS:
        if a not in declared:
            fail(f"actor {a} is not declared in {DOCS}/model/0-spec.c4")
    done("steps numbered in order, gate counts met, actors declared, no backticks")


def c_page():
    p = at(DOCS, "README.md")
    if not os.path.isfile(p):
        return fail(f"{DOCS}/README.md does not exist")
    lines = open(p, encoding="utf-8").read().splitlines()
    if not lines or lines[0] != MARK:
        fail("first line is not the likec4 export marker")
    heads = [x[4:].rstrip() for x in lines if x.startswith("### ")]
    miss = [h for h in HEADS if h not in heads]
    extra = [h for h in heads if h not in HEADS]
    for h in miss:
        fail(f"missing heading {h}")
    for h in extra:
        fail(f"extra heading {h}")
    if not miss and not extra and heads != HEADS:
        fail("headings are out of order")
    blocks = sum(x.strip() == "```mermaid" for x in lines)
    if blocks != len(HEADS):
        fail(f"{blocks} Mermaid blocks, expected {len(HEADS)}")
    done(f"{len(HEADS)} headings in order and {blocks} Mermaid blocks")


def c_readme():
    p = at("README.md")
    if not os.path.isfile(p):
        return fail("README.md does not exist")
    t = open(p, encoding="utf-8").read()
    need = [
        f"]({DOCS}/README.md)",
        f"npx -y likec4@{v} validate {DOCS}",
        f"npx -y likec4@{v} export markdown {DOCS}",
        "bash tests/test_harness_model.sh",
        f"claude mcp add --scope user likec4 -- npx -y @likec4/mcp@{v}",
        "22.22.3",
    ]
    for s in need:
        if s not in t:
            fail(f'missing "{s}"')
    done(f"{len(need)} links and commands found")


def c_nomcp():
    if os.path.exists(at(".mcp.json")):
        fail(".mcp.json must not exist")
    pj = at(".claude-plugin", "plugin.json")
    if os.path.isfile(pj) and "likec4" in open(pj, encoding="utf-8").read():
        fail(".claude-plugin/plugin.json names likec4")
    for dp, _, fn in os.walk(at(DOCS)):
        for f in fn:
            r = os.path.relpath(os.path.join(dp, f), at(DOCS)).replace(os.sep, "/")
            if not ALLOWED.match(r):
                fail(f"{DOCS}/{r} is not a model-format file")
    done("no .mcp.json, plugin.json does not name likec4, docs/harness holds only model-format files")


CHECKS = {
    "coverage-skills": c_skills,
    "coverage-agents": c_agents,
    "coverage-hooks": c_hooks,
    "coverage-statusline": c_statusline,
    "coverage-scripts": c_scripts,
    "coverage-procedures": c_procedures,
    "coverage-data": c_data,
    "missing": c_missing,
    "summaries": c_summaries,
    "links": c_links,
    "kinds": c_kinds,
    "vendored": c_vendored,
    "views": c_views,
    "page": c_page,
    "readme": c_readme,
    "nomcp": c_nomcp,
}
if name not in CHECKS:
    print(f"FAIL unknown check {name}")
    sys.exit(1)
if name in ("missing", "summaries", "links", "vendored", "views") and not glob.glob(at(DOCS, "model", "*.c4")):
    fail(f"{DOCS}/model has no .c4 files")
CHECKS[name]()
sys.exit(1 if bad else 0)
PY
}

for c in "$@"; do
  case "$c" in
    coverage) for s in $cov; do py "$s"; done ;;
    validate) validate ;;
    rebuild) rebuild ;;
    *) py "$c" ;;
  esac
done
exit $fail
